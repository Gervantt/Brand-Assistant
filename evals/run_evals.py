"""Run evals and write evals/results/{retrieval,generation}.json + summary tables.

    uv run python -m evals.run_evals retrieval
    uv run python -m evals.run_evals generation \\
        --models groq/openai/gpt-oss-20b,groq/openai/gpt-oss-120b --judge groq/openai/gpt-oss-120b

Requires the compose Postgres/Redis (`docker compose up -d postgres redis`); generation also
needs provider keys in .env.
"""

import argparse
import asyncio
import json
from datetime import UTC, datetime
from typing import Any

from brand_shared.logging_setup import configure_logging
from evals import generation_eval, retrieval_eval
from evals.common import RESULTS, load_cases, prepare_database

RETRIEVAL_COLUMNS = [
    ("config", "Configuration"),
    ("recall_at_1", "Recall@1"),
    ("recall_at_3", "Recall@3"),
    ("recall_at_5", "Recall@5"),
    ("mrr_at_10", "MRR@10"),
    ("found_rate_answerable", "Found (answerable)"),
    ("abstention_rate_offtopic", "Abstained (off-topic)"),
    ("p95_latency_ms", "p95, ms"),
]
GENERATION_COLUMNS = [
    ("model", "Model"),
    ("accuracy", "Accuracy"),
    ("partial", "Partial"),
    ("grounded", "Grounded"),
    ("abstention_offtopic", "Abstained (off-topic)"),
    ("false_abstention", "False abstention"),
    ("p95_latency_ms", "p95, ms"),
    ("cost_usd", "Cost, $"),
]


def cell(key: str, value: Any) -> str:
    if key == "cost_usd":
        return f"{value:.4f}"
    if key.endswith("latency_ms"):
        return f"{value:.0f}"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def markdown_table(rows: list[dict[str, Any]], columns: list[tuple[str, str]]) -> str:
    header = "| " + " | ".join(title for _, title in columns) + " |"
    divider = "|" + "|".join("---" for _ in columns) + "|"
    body = ["| " + " | ".join(cell(key, row[key]) for key, _ in columns) + " |" for row in rows]
    return "\n".join([header, divider, *body])


async def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("suite", choices=["retrieval", "generation"])
    parser.add_argument("--models", default="groq/openai/gpt-oss-20b,groq/openai/gpt-oss-120b")
    parser.add_argument("--judge", default="groq/openai/gpt-oss-120b")
    args = parser.parse_args()
    configure_logging("WARNING", json_logs=False)

    cases = load_cases()
    clients = await prepare_database()
    RESULTS.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    answerable = sum(c.answerable for c in cases)

    if args.suite == "retrieval":
        rows = await retrieval_eval.run(cases, clients)
        columns = RETRIEVAL_COLUMNS
    else:
        rows = await generation_eval.run(cases, clients, args.models.split(","), args.judge)
        columns = GENERATION_COLUMNS
    (RESULTS / f"{args.suite}.json").write_text(
        json.dumps({"date": stamp, "cases": len(cases), "rows": rows}, ensure_ascii=False, indent=2)
    )
    table = markdown_table(rows, columns)
    (RESULTS / f"{args.suite}.md").write_text(
        f"<!-- generated by evals/run_evals.py on {stamp}: {len(cases)} questions, "
        f"{answerable} answerable, {len(cases) - answerable} off-topic -->\n{table}\n"
    )
    print(f"\n{table}")


if __name__ == "__main__":
    asyncio.run(main())
